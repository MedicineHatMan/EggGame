// Draws the queue as textured quads in screen pixels then empties it
void gjPrintFlush(void)
{
	NJS_MATRIX scale;
	f32 ortho[16];
	NJS_MATRIX m;
	GjPrintEntry* e;

	GXInitTexObj(&gjDebugFontTex, gjDebugFontImage, 0x80, 0x80, 0, 0, 0, 0);
	GXInitTexObjLOD(&gjDebugFontTex, 0, 0, 0.0f, 0.0f, 0.0f, 0, 0, 0);
	GXLoadTexObj(&gjDebugFontTex, 0);
	PSMTXScale(scale, 0.0078125f, 0.0078125f, 1.0f);
	GXLoadTexMtxImm(scale, 0x1E, 1);
	GXSetNumTexGens(1);
	njPrintSetTexCoordGen(0, 1, 4, 0x1E);
	GXSetCullMode(0);
	C_MTXOrtho(ortho, 0.0f, 480.0f, 0.0f, 640.0f, 0.0f, 100.0f);
	GXSetProjection(ortho, 1);
	PSMTXIdentity(m);
	GXLoadPosMtxImm(m, 0);
	GXSetCurrentMtx(0);
	GXSetNumTevStages(1);
	GXSetTevOp(0, 0);
	GXSetTevOrder(0, 0, 0, 4);
	GXSetNumChans(1);
	GXSetChanCtrl(4, 0, 0, 1, 0, 2, 2);
	GXSetBlendMode(1, 4, 5, 0);
	GXSetZMode(1, 7, 1);
	GXClearVtxDesc();
	GXSetVtxDesc(9, 1);
	GXSetVtxDesc(11, 1);
	GXSetVtxDesc(13, 1);
	GXSetVtxAttrFmt(0, 9, 1, 3, 0);
	GXSetVtxAttrFmt(0, 11, 1, 5, 0);
	GXSetVtxAttrFmt(0, 13, 1, 3, 1);
	for (e = gjPrintEntries; e != gjPrintNextEntry; e++) {
		s32 x    = e->x;
		s32 y    = e->y;
		s32 size = (s16)e->size;
		s32 len;
		s32 col;
		s32 i;
		s32 right;
		s16 py;
		len = strlen(e->str);
		col = e->col;

		GXBegin(0x80, 0, len << 2);
		i     = 0;
		right = x + size;
		py    = y;
		for (; i < len; i++) {
			s32 c  = (s8)e->str[i];
			s16 u  = (c & 0xF) << 4;
			s16 v  = c & ~0xF;
			s16 px = x;
			u32 pc = col;

			njPrintGXPosition3s16(px, py, -1);
			njPrintGXColor1u32(pc);
			njPrintGXTexCoord2s16(u, v);
			njPrintGXPosition3s16(right, py, -1);
			njPrintGXColor1u32(pc);
			njPrintGXTexCoord2s16(u + 0x10, v);
			njPrintGXPosition3s16(right, y + size, -1);
			njPrintGXColor1u32(pc);
			njPrintGXTexCoord2s16(u + 0x10, v + 0x10);
			njPrintGXPosition3s16(px, y + size, -1);
			njPrintGXColor1u32(pc);
			njPrintGXTexCoord2s16(u, v + 0x10);
			right += size;
			x += size;
		}
		njPrintGXEnd();
	}
	GXSetZMode(1, 1, 1);
	gjPrintNextEntry = gjPrintEntries;
	gjPrintNextStr   = gjPrintStrings;
}

