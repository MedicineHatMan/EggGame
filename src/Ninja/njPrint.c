// 0x8020E9EC
// Prints digits digits of value with a sign if negative
void njPrintD(s32 loc, s32 value, s32 digits)
{
	s32 count = 0;
	s16 x;
	s16 y;
	GjPrintEntry* e;
	char* p;
	s32 d;

	if (loc & NJM_LOCATION_PIXELS) {
		x = (s16)((loc & 0x7FFF0000) >> 16);
		y = (s16)(loc & 0xFFFF);
	} else {
		x = (s16)((loc & 0x7FFF0000) >> 16) * gjPrintCharSize;
		y = (s16)(loc & 0xFFFF) * gjPrintCharSize;
	}
	e                = gjPrintNextEntry;
	gjPrintNextEntry = e + 1;
	e->x             = x;
	e->y             = y;
	e->size          = gjPrintCharSize;
	e->col           = gjPrintColor;
	e->str           = gjPrintNextStr;
	p                = gjPrintNextStr;
	if (value < 0) {
		*p++ = '-';
		value *= -1;
		count = 1;
	}
	while (digits > 0) {
		switch (digits) {
		case 1:
			d = value % 10;
			break;
		case 2:
			d = value / 10;
			value -= d * 10;
			break;
		case 3:
			d = value / 100;
			value -= d * 100;
			break;
		case 4:
			d = value / 1000;
			value -= d * 1000;
			break;
		case 5:
			d = value / 10000;
			value -= d * 10000;
			break;
		case 6:
			d = value / 100000;
			value -= d * 100000;
			break;
		case 7:
			d = value / 1000000;
			value -= d * 1000000;
			break;
		case 8:
			d = value / 10000000;
			value -= d * 10000000;
			break;
		case 9:
			d = value / 100000000;
			value -= d * 100000000;
			break;
		default:
			d = value / 1000000000;
			value -= d * 1000000000;
			break;
		}
		if (d > 9) {
			d = 0;
		}
		*p++ = (s8)(u8)(d + '0');
		digits--;
		count++;
	}
	gjPrintNextStr[count] = 0;
	gjPrintNextStr += count + 1;
}

// 0x8020ECE0
// Pads the whole part to width digits
void njPrintF(s32 loc, s32 width, f32 value)
{
	s16 x;
	s16 y;
	GjPrintEntry* e;
	char buf[0x18];
	char* p;
	s32 len;
	s32 dot;
	s32 pad;
	s32 total;
	s32 i;

	if (loc & NJM_LOCATION_PIXELS) {
		x = (s16)((loc & 0x7FFF0000) >> 16);
		y = (s16)(loc & 0xFFFF);
	} else {
		x = (s16)((loc & 0x7FFF0000) >> 16) * gjPrintCharSize;
		y = (s16)(loc & 0xFFFF) * gjPrintCharSize;
	}
	e                = gjPrintNextEntry;
	gjPrintNextEntry = e + 1;
	e->x             = x;
	e->y             = y;
	e->size          = gjPrintCharSize;
	e->col           = gjPrintColor;
	e->str           = gjPrintNextStr;
	p                = gjPrintNextStr;
	if (value < 0.0f) {
		*p++ = '-';
		value *= -1.0f;
	}
	sprintf(buf, njFloatFormat, 5, value);
	len = strlen(buf);
	for (dot = 0; dot < len; dot++) {
		if (buf[dot] == '.') {
			break;
		}
	}
	pad   = width - dot;
	total = len + pad;
	for (i = total; i >= pad; i--) {
		buf[i] = buf[len--];
	}
	for (i = 0; i < pad; i++) {
		buf[i] = '0';
	}
	for (i = 0; i < total; i++) {
		*p++ = buf[i];
	}
	gjPrintNextStr[total] = 0;
	gjPrintNextStr += total + 1;
}

