/* Takes a free note slot searching from the last one taken */
// 0x80231C6C
GCAX_NOTE* gcaxNoteAlloc(void)
{
	int i;
	int n;

	for (i = 0; i < GCAX_NOTE_MAX; i++) {
		n = (gcax_work->note_rover + i) % GCAX_NOTE_MAX;
		if (gcax_work->note[n].active == 0) {
			gcax_work->note_rover = n + 1;
			return &gcax_work->note[n];
		}
	}
	return 0;
}

/* Takes the slot of a note with no higher priority stopping that note */
// 0x80231CF8
GCAX_NOTE* gcaxNoteSteal(int prio)
{
	int i;
	int n;

	for (i = 0; i < GCAX_NOTE_MAX; i++) {
		n = (gcax_work->note_rover + i) % GCAX_NOTE_MAX;
		if (gcax_work->note[n].active != 0 && gcax_work->note[n].prio <= prio) {
			gcaxNoteRelease(&gcax_work->note[n]);
			gcax_work->note_rover = n + 1;
			return &gcax_work->note[n];
		}
	}
	return 0;
}

/* Stops notes of no higher priority until need voices are free */
// 0x80231DC8
GCAX_NOTE* gcaxNoteStealVoices(int prio, int need)
{
	GCAX_NOTE* note;
	int i;
	int rest;
	int n;

	note = 0;
	if (need <= 0) {
		return gcaxNoteSteal(prio);
	}
	rest = need;
	while (rest > 0) {
		for (i = 0; i < GCAX_NOTE_MAX; i++) {
			n = (gcax_work->note_rover + i) % GCAX_NOTE_MAX;
			if (gcax_work->note[n].active != 0 && gcax_work->note[n].prio <= prio) {
				rest -= gcaxNoteCountVoices(&gcax_work->note[n]);
				gcaxNoteRelease(&gcax_work->note[n]);
				gcax_work->note_rover = n + 1;
				note = &gcax_work->note[n];
				break;
			}
		}
		if (rest == need) {
			break;
		}
	}
	return note;
}

// 0x80231EE0
void gcaxNoteFree(GCAX_NOTE* note)
{
	if (note->voices != 0) {
		gcaxVoiceListClear(&note->voices);
	}
	note->active = 0;
}

/* Takes a note off its port's list which frees it */
// 0x80231F24
void gcaxNoteRelease(GCAX_NOTE* note)
{
	GCAX_LINK** list;
	GCAX_LINK* link;

	if (note == 0) {
		return;
	}
	if (note->port->notes == 0) {
		return;
	}
	list = &note->port->notes;
	link = gcaxNoteListFind(list, note);
	if (link != 0) {
		gcaxNoteListDelete(list, link);
	}
}

// 0x80231FA0
int gcaxNoteCount(void)
{
	int n;
	int i;

	n = 0;
	if (gcax_work != 0) {
		for (i = 0; i < GCAX_NOTE_MAX; i++) {
			if (gcax_work->note[i].active != 0) {
				n++;
			}
		}
	}
	return n;
}

/* Starts a note on a port's channel */
// 0x80232000
GCAX_NOTE* gcaxNoteOn(void* port, int ch, int key, int vel, int prio)
{
	GCAX_NOTE* note;
	GCAX_VOICE* voice;
	u32 bank;
	u32 prog;
	int need;
	int over;
	int i;
	GCAX_LINK* ok;

	note = 0;
	bank = ((GCAX_PORT*)port)->chan[ch].bank;
	prog = ((GCAX_PORT*)port)->chan[ch].prog;
	need = gcaxSndCountVoices(bank, prog, key);
	if (need <= 0) {
		return 0;
	}
	over = need - (gcax_work->max_voice - gcaxVoiceCountUsed());
	if (over < 0) {
		over = 0;
	}
	if (over != 0) {
		note = gcaxNoteStealVoices(prio, over);
		if (note == 0) {
			return 0;
		}
	} else {
		note = gcaxNoteAlloc();
		if (note == 0) {
			note = gcaxNoteSteal(prio);
			if (note == 0) {
				return 0;
			}
		}
	}
	note->port = (GCAX_PORT*)port;
	note->key = key;
	note->chan = ch;
	note->vel = vel;
	note->prio = prio;
	note->nvoice = need;
	note->active = 1;
	note->voices = 0;
	for (i = 0; i < need; i++) {
		voice = gcaxVoiceAlloc(note, 5, 0);
		if (voice == 0) {
			gcaxNoteRelease(note);
			return 0;
		}
		ok = gcaxVoiceListAdd(&note->voices, voice);
		if (ok == 0) {
			gcaxNoteRelease(note);
			return 0;
		}
	}
	gcaxSndStartVoices(&note->voices, bank, prog, key, vel);
	return note;
}
