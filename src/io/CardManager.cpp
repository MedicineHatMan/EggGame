// 0x8019FB74
void CardManager::update()
{
	if (mWorker != 0) {
		mWorker->update();
	} else {
		return;
	}
	do {
		syncWorker();
		mChanged = 0;
		runState(mState, 1);
	} while (mChanged != 0);
	if (mWant != 0) {
		handleState(mState, 4);
		mWant = 0;
	}
}

